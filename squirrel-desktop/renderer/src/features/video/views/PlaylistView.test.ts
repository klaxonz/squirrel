function createPlaylistStore() {
  return {
    playlists: ref([playlist]),
    loading: ref(false),
    loadingItems: ref(false),
    error: ref<string | null>(null),
    activePlaylist: ref<PlaylistDetail | null>(playlist),
    activePlaylistItems: ref([item]),
    currentVideoId: ref<number | string | null>(null),
    setCurrentVideo: vi.fn(),
    fetchPlaylists: vi.fn().mockResolvedValue(undefined),
    loadAndSetPlaylist: vi.fn().mockResolvedValue([item]),
    create: vi.fn().mockResolvedValue(playlist),
    update: vi.fn().mockResolvedValue(playlist),
    remove: vi.fn().mockResolvedValue(true),
    removeVideo: vi.fn().mockResolvedValue(true),
  }
}

async function mountPlaylistView() {
  const host = document.createElement('div')
  document.body.append(host)
  const app = createApp(PlaylistView)
  mountedApps.push(app)
  app.mount(host)
  await nextTick()
  await nextTick()
  return host
}

function nativeKeyboardActivate(button: HTMLButtonElement, key: 'Enter' | ' ') {
  button.dispatchEvent(new KeyboardEvent('keydown', { key, bubbles: true, cancelable: true }))
  button.dispatchEvent(new KeyboardEvent('keyup', { key, bubbles: true, cancelable: true }))
  // jsdom does not synthesize the click generated by native keyboard activation.
  button.click()
}

beforeEach(() => {
  mocks.playlistStore = createPlaylistStore()
})

afterEach(() => {
  mountedApps.splice(0).forEach(app => app.unmount())
  document.body.replaceChildren()
  vi.clearAllMocks()
})

describe('PlaylistView queue row semantics', () => {
  it('keeps native playback and remove controls keyboard-independent', async () => {
    const host = await mountPlaylistView()
    const shell = host.querySelector<HTMLElement>('article.playlist-item-shell')!
    const playback = shell.querySelector<HTMLButtonElement>('.app-content-row__primary')!
    const remove = shell.querySelector<HTMLButtonElement>('.playlist-item-remove')!
    const store = mocks.playlistStore as ReturnType<typeof createPlaylistStore>

    expect(shell.hasAttribute('role')).toBe(false)
    expect(shell.hasAttribute('tabindex')).toBe(false)
    expect(playback.type).toBe('button')
    expect(remove.type).toBe('button')
    expect(playback.contains(remove)).toBe(false)
    expect(playback.parentElement).toBe(remove.parentElement?.parentElement)

    nativeKeyboardActivate(remove, 'Enter')
    nativeKeyboardActivate(remove, ' ')
    await nextTick()

    expect(store.removeVideo).toHaveBeenCalledTimes(2)
    expect(store.removeVideo).toHaveBeenCalledWith(playlist.id, item.video_id)
    expect(store.setCurrentVideo).not.toHaveBeenCalled()
    expect(mocks.routerPush).not.toHaveBeenCalled()

    nativeKeyboardActivate(playback, 'Enter')
    nativeKeyboardActivate(playback, ' ')
    await nextTick()

    expect(store.setCurrentVideo).toHaveBeenCalledTimes(2)
    expect(store.setCurrentVideo).toHaveBeenCalledWith(item.video?.id)
    expect(mocks.routerPush).toHaveBeenCalledTimes(2)
    expect(mocks.routerPush).toHaveBeenCalledWith(`/video/${item.video?.id}`)
    expect(store.removeVideo).toHaveBeenCalledTimes(2)
  })
})

describe('PlaylistView editor fields', () => {
  it('associates explicit labels and applies required semantics only to the name', async () => {
    const host = await mountPlaylistView()
    const createButton = Array.from(host.querySelectorAll<HTMLButtonElement>('button'))
      .find(button => button.getAttribute('aria-label') === '新建播放列表')!

    createButton.click()
    await nextTick()

    const name = host.querySelector<HTMLInputElement>('#playlist-editor-name')!
    const description = host.querySelector<HTMLTextAreaElement>('#playlist-editor-description')!
    const nameLabel = host.querySelector<HTMLLabelElement>('label[for="playlist-editor-name"]')!
    const descriptionLabel = host.querySelector<HTMLLabelElement>('label[for="playlist-editor-description"]')!

    expect(nameLabel.textContent).toContain('列表名称')
    expect(descriptionLabel.textContent).toContain('描述')
    expect(name.getAttribute('aria-labelledby')).toBe(nameLabel.id)
    expect(description.getAttribute('aria-labelledby')).toBe(descriptionLabel.id)
    expect(name.required).toBe(true)
    expect(description.required).toBe(false)
    expect(nameLabel.querySelector('[aria-hidden="true"]')?.textContent).toBe('*')
    expect(descriptionLabel.querySelector('[aria-hidden="true"]')).toBeNull()
  })
})
